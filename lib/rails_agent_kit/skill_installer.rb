# frozen_string_literal: true

require "fileutils"

module RailsAgentKit
  # Installs the agent skills bundled with the gem (skills/<name>/SKILL.md) into a Rails app.
  #
  # Agents with skill folders get a copy of each SKILL.md:
  #
  #   cursor  -> .cursor/skills/<name>/SKILL.md
  #   claude  -> .claude/skills/<name>/SKILL.md
  #
  # Agents that read a single instructions file get the skills rendered into a managed block between
  # MARKER_START and MARKER_END. Content outside the block is never touched:
  #
  #   codex   -> AGENTS.md (also read by Cursor, Copilot, Windsurf, Zed and others)
  #   copilot -> .github/copilot-instructions.md
  #   gemini  -> GEMINI.md
  class SkillInstaller
    SKILLS_DIR = File.expand_path("../../skills", __dir__)
    SKILL_DIRS = {
      "cursor" => ".cursor/skills",
      "claude" => ".claude/skills"
    }.freeze
    INSTRUCTION_FILES = {
      "codex" => "AGENTS.md",
      "copilot" => ".github/copilot-instructions.md",
      "gemini" => "GEMINI.md"
    }.freeze
    TARGETS = SKILL_DIRS.merge(INSTRUCTION_FILES).freeze
    MARKER_START = "<!-- rails-agent-kit:start -->"
    MARKER_END = "<!-- rails-agent-kit:end -->"

    Result = Struct.new(:skill, :path, :status, :message, keyword_init: true)

    def self.available_skills
      Dir.glob(File.join(SKILLS_DIR, "*", "SKILL.md")).map { |f| File.basename(File.dirname(f)) }.sort
    end

    # The managed block for instruction-file agents: the skills' bodies without front matter, with every
    # heading one level deeper so they nest under the file's own top-level heading.
    def self.render_block(skills)
      bodies = skills.map { |name| demote_headings(strip_front_matter(File.read(skill_source(name)))).strip }
      [
        MARKER_START,
        "<!-- Generated by `rails-agent-kit install-skills`. Edits inside this block are replaced on the next run. -->",
        "",
        bodies.join("\n\n"),
        MARKER_END
      ].join("\n") + "\n"
    end

    def self.skill_source(name)
      source = File.join(SKILLS_DIR, name, "SKILL.md")
      raise Error, "unknown skill #{name.inspect} (available: #{available_skills.join(', ')})" unless File.file?(source)

      source
    end

    def self.strip_front_matter(text)
      text.sub(/\A---\s*\n.*?\n---\s*\n/m, "")
    end

    def self.demote_headings(text)
      in_fence = false
      text.lines.map do |line|
        in_fence = !in_fence if line.start_with?("```", "~~~")
        !in_fence && line.match?(/\A\#{1,5} /) ? "##{line}" : line
      end.join
    end

    def initialize(root, agent: "cursor", force: false)
      @root = File.expand_path(root)
      @agent = agent.to_s
      @force = force
      raise Error, "unknown agent #{@agent.inspect} (supported: #{TARGETS.keys.join(', ')})" unless TARGETS.key?(@agent)
    end

    # Installs the named skills (default: all bundled skills). Returns one Result per written path with status
    # :created, :added (block appended to an existing file), :updated, :unchanged or :skipped. A skill copy you
    # have edited is skipped unless force: true; a managed block is always brought up to date.
    def install(skills = self.class.available_skills)
      run(skills, write: true)
    end

    # Same statuses as #install, without writing anything.
    def plan(skills = self.class.available_skills)
      run(skills, write: false)
    end

    private

    def run(skills, write:)
      skills.each { |name| self.class.skill_source(name) }
      if INSTRUCTION_FILES.key?(@agent)
        [install_block(skills, write: write)]
      else
        skills.map { |name| install_skill(name, write: write) }
      end
    end

    def install_skill(name, write:)
      dest = File.join(@root, SKILL_DIRS.fetch(@agent), name, "SKILL.md")
      content = File.read(self.class.skill_source(name))
      status =
        if !File.exist?(dest) then :created
        elsif File.read(dest) == content then :unchanged
        elsif @force then :updated
        else :skipped
        end

      write_file(dest, content) if write && %i[created updated].include?(status)
      Result.new(skill: name, path: dest, status: status)
    end

    def install_block(skills, write:)
      dest = File.join(@root, INSTRUCTION_FILES.fetch(@agent))
      block = self.class.render_block(skills)
      result = ->(status, message = nil) { Result.new(skill: skills.join(", "), path: dest, status: status, message: message) }
      return result.call(:created).tap { write_file(dest, block) if write } unless File.exist?(dest)

      current = File.read(dest)
      start = current.index(MARKER_START)
      finish = start && current.index(MARKER_END, start)
      if start.nil? && !current.include?(MARKER_END)
        separator = current.empty? || current.end_with?("\n\n") ? "" : (current.end_with?("\n") ? "\n" : "\n\n")
        write_file(dest, current + separator + block) if write
        return result.call(:added)
      end
      return result.call(:skipped, "found an unmatched rails-agent-kit marker; fix or remove it") if finish.nil?

      stop = finish + MARKER_END.length
      stop += 1 if current[stop] == "\n"
      return result.call(:unchanged) if current[start...stop] == block

      write_file(dest, current[0...start] + block + current[stop..]) if write
      result.call(:updated)
    end

    def write_file(dest, content)
      FileUtils.mkdir_p(File.dirname(dest))
      File.write(dest, content)
    end
  end
end
